-- The web app's schema on Postgres, for the load-test comparison only (the
-- default build is SQLite-only). It mirrors migrations/sqlite/20261010000000_init.sql
-- with no change_log: there is no sync worker in this mode.
--
-- Text is COLLATE "C" so that ORDER BY sorts bytewise (like SQLite's BINARY) and
-- ILIKE folds ASCII case only (like SQLite's LIKE). Timestamps stay Unix seconds.
-- Every UNIQUE index is named: db.rs maps the name to the `table.column` string the
-- services compare against.

CREATE EXTENSION IF NOT EXISTS pg_trgm;  -- trusted: the database owner may create it

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT COLLATE "C" NOT NULL,
    password_hash TEXT COLLATE "C" NOT NULL,
    created_at    BIGINT NOT NULL
);
-- SQLite declares the column COLLATE NOCASE (ASCII folding); lower() under "C" does the same.
CREATE UNIQUE INDEX uq_users_username ON users (lower(username));

CREATE TABLE sessions (
    token_hash TEXT COLLATE "C" PRIMARY KEY,   -- hex(SHA-256(raw token)); raw token only in the cookie
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX idx_sessions_expires_at ON sessions(expires_at);

CREATE TABLE books (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          TEXT COLLATE "C" NOT NULL,
    author         TEXT COLLATE "C" NOT NULL,
    isbn           TEXT COLLATE "C",           -- normalized digits (+ 'X'), NULL if unknown
    published_year BIGINT,
    total_copies   BIGINT NOT NULL CHECK (total_copies BETWEEN 1 AND 1000),
    created_at     BIGINT NOT NULL,
    updated_at     BIGINT NOT NULL
);
-- Not partial like SQLite's: NULLs are distinct in a Postgres unique index anyway, and a
-- partial `WHERE isbn IS NOT NULL` index makes the planner skip the trigram indexes for
-- searches that test isbn twice (measured: seq scan at 100k rows instead of bitmap scans).
CREATE UNIQUE INDEX uq_books_isbn ON books(isbn);
CREATE INDEX idx_books_title_id ON books(title, id);
-- Trigram indexes serve the ILIKE '%...%' search.
CREATE INDEX idx_books_title_trgm  ON books USING gin (title  gin_trgm_ops);
CREATE INDEX idx_books_author_trgm ON books USING gin (author gin_trgm_ops);
CREATE INDEX idx_books_isbn_trgm   ON books USING gin (isbn   gin_trgm_ops);

CREATE TABLE members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT COLLATE "C" NOT NULL,
    email      TEXT COLLATE "C" NOT NULL,      -- stored lowercased
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX uq_members_email ON members(email);
CREATE INDEX idx_members_name_id ON members(name, id);

CREATE TABLE loans (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     BIGINT NOT NULL REFERENCES books(id)   ON DELETE CASCADE,
    member_id   BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    borrowed_at BIGINT NOT NULL,
    due_at      BIGINT NOT NULL,
    returned_at BIGINT
);
CREATE INDEX idx_loans_active_book   ON loans(book_id)   WHERE returned_at IS NULL;
CREATE INDEX idx_loans_active_member ON loans(member_id) WHERE returned_at IS NULL;
CREATE INDEX idx_loans_active_due    ON loans(due_at)    WHERE returned_at IS NULL;
CREATE INDEX idx_loans_due_at_id     ON loans(due_at, id);
CREATE INDEX idx_loans_returned_at_id ON loans(returned_at DESC, id DESC) WHERE returned_at IS NOT NULL;
